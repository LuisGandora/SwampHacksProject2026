"""Hazard Index model: one row per site per day, one XGBoost classifier per hazard category.

    python -m ml.hazard_model train     # build the site-day table from Tiger, train, evaluate, save models
    python -m ml.hazard_model score     # score today ('now') and tomorrow ('next_day') into hazard_scores

Label: did a recorded hazard happen near the site that day? (a NOAA storm event, or an OSHA weather injury,
within the category's history_radius_mi, i.e. the rows in site_hazard_events.)
Features: only what a forecast can also give us (daily weather at the site's station, the rain of the days
before, season, location), so the same model scores tomorrow from the NWS forecast.

Hazard Index = 10 x P(at least one hazard category occurs) = 10 x (1 - prod(1 - p_category)).
Category scores = 10 x p_category, each with the features that pushed it up the most (XGBoost contributions).
Every number is computed here; nothing is generated by an LLM.
"""
import datetime as dt
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score
import xgboost as xgb
from xgboost import XGBClassifier

from db.setup_db import database_url

MODEL_DIR = Path(__file__).resolve().parent / "models"
CATEGORIES = ["severe_storm", "tropical", "flooding", "lightning", "extreme_heat", "extreme_cold", "high_wind"]
FEATURES = ["max_temp_f", "min_temp_f", "max_heat_index_f", "precip_in", "rain_prior_6d_in", "max_gust_kt",
            "doy_sin", "doy_cos", "lat", "lon"]
TRAIN_END = pd.Timestamp("2024-12-31")  # train on the past, test on 2025-26 (never a random split: storms span sites)
MODEL_VERSION = "site-day-xgb-v2"
WEATHER_DRIVERS = {"max_temp_f", "min_temp_f", "max_heat_index_f", "precip_in", "rain_prior_6d_in", "max_gust_kt"}
LABELS = {  # human names for drivers in reports
    "max_temp_f": "high temperature", "min_temp_f": "low temperature", "max_heat_index_f": "heat index",
    "precip_in": "rain that day", "rain_prior_6d_in": "rain over the previous 6 days", "max_gust_kt": "wind gusts",
    "doy_sin": "time of year", "doy_cos": "time of year", "lat": "location", "lon": "location",
}


def query(conn, sql, params=()):
    return pd.DataFrame(conn.execute(sql, params).fetchall())


def add_season(df):
    doy = pd.to_datetime(df["day"]).dt.dayofyear
    df["doy_sin"], df["doy_cos"] = np.sin(2 * np.pi * doy / 365.25), np.cos(2 * np.pi * doy / 365.25)
    return df


def load_training(conn):
    """Site-day table: station weather joined to sites, plus 0/1 labels per category."""
    w = query(conn, "SELECT station_id, day, max_temp_f, min_temp_f, max_heat_index_f, precip_in, max_gust_kt "
                    "FROM weather_daily ORDER BY station_id, day")
    w["day"] = pd.to_datetime(w["day"])
    for c in ["max_temp_f", "min_temp_f", "max_heat_index_f", "precip_in", "max_gust_kt"]:
        w[c] = w[c].astype(float)
    w["rain_prior_6d_in"] = (w.set_index("day").groupby("station_id")["precip_in"]
                             .rolling("6D", closed="left").sum().reset_index(level=0, drop=True).values)
    sites = query(conn, "SELECT site_id, weather_station_id AS station_id, ST_Y(geog::geometry) AS lat, "
                        "ST_X(geog::geometry) AS lon FROM sites WHERE weather_station_id IS NOT NULL")
    df = sites.merge(w, on="station_id")
    labels = query(conn, """
        SELECT h.site_id, h.category, (h.event_time AT TIME ZONE s.timezone)::date AS day, count(*) AS n
          FROM site_hazard_events h JOIN sites s USING (site_id)
         WHERE h.category = ANY (%s) AND (h.source = 'noaa_storm_event' OR h.source = 'osha_injury')
           AND h.event_time >= (SELECT min(day) FROM weather_daily)
         GROUP BY 1, 2, 3""", (CATEGORIES,))
    labels["day"] = pd.to_datetime(labels["day"])
    y = labels.pivot_table(index=["site_id", "day"], columns="category", values="n", aggfunc="sum").reindex(
        columns=CATEGORIES).fillna(0).gt(0).astype(int).add_prefix("y_").reset_index()
    df = df.merge(y, on=["site_id", "day"], how="left")
    df[[f"y_{c}" for c in CATEGORIES]] = df[[f"y_{c}" for c in CATEGORIES]].fillna(0).astype(int)
    return add_season(df)


def new_model():
    # No class weighting: we want probabilities that mean what they say (a 0.3 is ~30% of such days).
    return XGBClassifier(n_estimators=400, max_depth=5, learning_rate=0.05, subsample=0.8, colsample_bytree=0.8,
                         min_child_weight=5, tree_method="hist", eval_metric="logloss", n_jobs=-1, random_state=42)


def train(conn):
    df = load_training(conn)
    train_mask = df["day"] <= TRAIN_END
    print(f"{len(df):,} site-days ({train_mask.sum():,} train <= {TRAIN_END.date()}, {(~train_mask).sum():,} test)")
    MODEL_DIR.mkdir(exist_ok=True)
    metrics = {"version": MODEL_VERSION, "features": FEATURES, "trained_at": dt.datetime.now().isoformat(),
               "rows": int(len(df)), "categories": {}}
    for cat in CATEGORIES:
        y = df[f"y_{cat}"]
        m = new_model().fit(df.loc[train_mask, FEATURES], y[train_mask])
        p = m.predict_proba(df.loc[~train_mask, FEATURES])[:, 1]
        yt = y[~train_mask]
        res = {"base_rate": round(float(yt.mean()), 5), "positives_test": int(yt.sum()),
               "roc_auc": round(float(roc_auc_score(yt, p)), 3) if yt.nunique() > 1 else None,
               "pr_auc": round(float(average_precision_score(yt, p)), 3) if yt.nunique() > 1 else None,
               "brier": round(float(brier_score_loss(yt, p)), 5),
               "mean_predicted": round(float(p.mean()), 5),
               "calibration_ratio": round(float(p.mean() / yt.mean()), 2) if yt.mean() > 0 else None}
        metrics["categories"][cat] = res
        print(f"  {cat:13} test AUC {res['roc_auc']}  PR-AUC {res['pr_auc']} (base rate {res['base_rate']:.4f}, "
              f"{res['positives_test']} positive site-days, predicted/observed {res['calibration_ratio']})")
        # production model: same settings, refit on all years
        new_model().fit(df[FEATURES], y).save_model(MODEL_DIR / f"{cat}.json")
    imp = {}
    for cat in CATEGORIES:
        b = load_model(cat).get_booster().get_score(importance_type="gain")
        for f, g in b.items():
            imp[f] = imp.get(f, 0) + g
    total = sum(imp.values())
    metrics["feature_gain_share"] = {f: round(g / total, 3) for f, g in sorted(imp.items(), key=lambda kv: -kv[1])}
    print("  feature gain share:", metrics["feature_gain_share"])
    (MODEL_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2))
    return metrics


def load_model(cat):
    m = XGBClassifier()
    m.load_model(MODEL_DIR / f"{cat}.json")
    return m


def predict(df, models=None):
    """Adds p_<cat>, score, category_scores (with top drivers) to a feature frame."""
    models = models or {c: load_model(c) for c in CATEGORIES}
    X = df[FEATURES].astype(float)
    none = np.ones(len(df))
    breakdown = [dict() for _ in range(len(df))]
    for cat, m in models.items():
        p = m.predict_proba(X)[:, 1]
        df[f"p_{cat}"] = p
        none *= 1 - p
        contrib = m.get_booster().predict(xgb.DMatrix(X), pred_contribs=True)[:, :-1]
        for i in range(len(df)):
            top = sorted(((contrib[i, j], FEATURES[j]) for j in range(len(FEATURES))
                          if FEATURES[j] in WEATHER_DRIVERS), reverse=True)[:3]  # location/season are context
            breakdown[i][cat] = {"score": round(float(p[i]) * 10, 1),
                                 "drivers": [{"feature": f, "label": LABELS[f], "value": round(float(X.iloc[i][f]), 2)}
                                             for c, f in top if c > 0]}
    df["score"] = np.round((1 - none) * 10, 1)
    df["category_scores"] = breakdown
    return df


FORECAST_DAY = """
WITH s AS (SELECT site_id, timezone, weather_station_id AS st, geog, (now() AT TIME ZONE timezone)::date AS today
             FROM sites),
fc AS (   -- NWS hourly forecast, today and tomorrow (one row per past hour survives each refresh)
    SELECT f.site_id, date_trunc('hour', f.valid_at) AS h, max(f.temp_f) AS t,
           max(coalesce(f.heat_index_f, f.temp_f)) AS hi, max(f.precip_in) AS p, max(f.wind_gust_mph) AS g
      FROM weather_forecasts f JOIN s USING (site_id)
     WHERE f.valid_at >= s.today::timestamp AT TIME ZONE s.timezone
       AND f.valid_at < (s.today + 2)::timestamp AT TIME ZONE s.timezone
     GROUP BY 1, 2
), ob AS (  -- what the station actually measured so far today (hourly rain repeats between reports: take max)
    SELECT o.site_id, date_trunc('hour', o.observed_at) AS h, max(o.temp_f) AS t,
           max(coalesce(o.heat_index_f, o.temp_f)) AS hi, max(o.precip_1h_in) AS p, max(o.wind_gust_mph) AS g
      FROM weather_observations o JOIN s USING (site_id)
     WHERE o.observed_at >= s.today::timestamp AT TIME ZONE s.timezone AND o.observed_at < now()
     GROUP BY 1, 2
), hrs AS (  -- observed beats forecast for the same hour
    SELECT coalesce(ob.site_id, fc.site_id) AS site_id, coalesce(ob.h, fc.h) AS h, coalesce(ob.t, fc.t) AS t,
           coalesce(ob.hi, fc.hi) AS hi, coalesce(ob.p, fc.p) AS p, coalesce(ob.g, fc.g) AS g
      FROM fc FULL JOIN ob ON ob.site_id = fc.site_id AND ob.h = fc.h
), days AS (
    SELECT x.site_id, (x.h AT TIME ZONE s.timezone)::date AS day, max(x.t) AS max_temp_f, min(x.t) AS min_temp_f,
           max(x.hi) AS max_heat_index_f, coalesce(sum(x.p), 0) AS precip_in, max(x.g) / 1.15078 AS max_gust_kt,
           count(*) AS hours
      FROM hrs x JOIN s USING (site_id) GROUP BY 1, 2
)
SELECT s.site_id, s.timezone, ST_Y(s.geog::geometry) AS lat, ST_X(s.geog::geometry) AS lon, d.day, d.max_temp_f,
       d.min_temp_f, d.max_heat_index_f, d.precip_in, d.max_gust_kt, d.hours,
       coalesce((SELECT sum(w.precip_in) FROM weather_daily w WHERE w.station_id = s.st
                  AND w.day >= d.day - 6 AND w.day < least(d.day, s.today)), 0)
     + coalesce((SELECT sum(x.precip_in) FROM days x WHERE x.site_id = d.site_id
                  AND x.day >= s.today AND x.day < d.day), 0) AS rain_prior_6d_in
  FROM days d JOIN s USING (site_id)
 WHERE d.day = s.today + %(offset)s
"""


def expected_crew_cost(df, a):
    """Expected crew-hours lost and cost per site-day from the category probabilities.

    sum(p_category x hours_lost_<category>), capped at one shift, x crew size (x loaded cost for dollars).
    Every input except p comes from economic_assumptions, so this is an estimate labeled as such.
    """
    hours = sum(df[f"p_{c}"] * a.get(f"hours_lost_{c}", 0.0) for c in CATEGORIES).clip(upper=a.get("shift_hours", 10.0))
    df["expected_crew_hours_lost"] = (hours * a.get("crew_size", 0.0)).round(2)
    df["expected_cost_usd"] = (df["expected_crew_hours_lost"] * a.get("loaded_cost_per_hour", 0.0)).round(0)
    return df


def score(conn):
    """Score today and tomorrow for every site from the NWS forecast, write hazard_scores."""
    models = {c: load_model(c) for c in CATEGORIES}
    assumptions = {r["key"]: float(r["value"]) for r in conn.execute("SELECT key, value FROM economic_assumptions")}
    written = 0
    for horizon, offset in (("now", 0), ("next_day", 1)):
        df = query(conn, FORECAST_DAY, {"offset": offset})
        if df.empty:
            continue
        df["rain_prior_6d_in"] = df["rain_prior_6d_in"].astype(float).fillna(0)
        df = expected_crew_cost(predict(add_season(df), models), assumptions)
        rows = [(int(r.site_id), r.day, r.timezone, horizon, float(r.score),
                 Jsonb({**r.category_scores, "_meta": {
                     "forecast_hours": int(r.hours), "expected_crew_hours_lost": float(r.expected_crew_hours_lost),
                     "expected_cost_usd": float(r.expected_cost_usd),
                     "economic_note": "estimate from economic_assumptions (labeled assumptions)"}}), MODEL_VERSION)
                for r in df.itertuples()]
        conn.cursor().executemany(
            "INSERT INTO hazard_scores (site_id, scored_for, horizon, score, category_scores, model_version) "
            "VALUES (%s, (%s::date)::timestamp AT TIME ZONE %s, %s, %s, %s, %s) "
            "ON CONFLICT (site_id, scored_for, horizon) DO UPDATE SET score = EXCLUDED.score, "
            "category_scores = EXCLUDED.category_scores, model_version = EXCLUDED.model_version, created_at = now()",
            rows)
        written += len(rows)
    return f"{written} scores written"


def main():
    with psycopg.connect(database_url(), row_factory=dict_row) as conn:
        if sys.argv[1:] == ["train"]:
            train(conn)
        elif sys.argv[1:] == ["score"]:
            print(score(conn))
        else:
            raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
